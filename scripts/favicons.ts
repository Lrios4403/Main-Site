// Fetches a favicon for every host linked from the posts' and site pages'
// resources and credits, once, at development time, into public/favicons/,
// and writes lib/favicons.generated.ts listing the hosts that have one. The
// link cards and the sidebar show them from there, so visitors never hit a
// third-party favicon service.
//
//   bun scripts/favicons.ts
import { readFileSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";

const SOURCES = ["lib/posts.ts", "lib/site-pages.ts"];
const OUT_DIR = "public/favicons";
const MANIFEST = "lib/favicons.generated.ts";

const hosts = new Set<string>();
for (const file of SOURCES) {
  for (const match of readFileSync(file, "utf8").matchAll(/href:\s*"(https?:\/\/[^"]+)"/g)) {
    hosts.add(new URL(match[1]).hostname);
  }
}

await mkdir(OUT_DIR, { recursive: true });
const have: string[] = [];
for (const host of [...hosts].sort()) {
  const response = await fetch(`https://www.google.com/s2/favicons?domain=${host}&sz=64`);
  const type = response.headers.get("content-type") ?? "";
  if (!response.ok || !type.startsWith("image/")) {
    console.log(`no favicon for ${host} (${response.status} ${type})`);
    continue;
  }
  await writeFile(`${OUT_DIR}/${host}.png`, Buffer.from(await response.arrayBuffer()));
  have.push(host);
  console.log(`saved ${host}`);
}

await writeFile(MANIFEST, [
  "// Generated by scripts/favicons.ts: the hosts with a favicon in public/favicons/.",
  "// Rerun the script after adding a resource on a new host.",
  `export const FAVICON_HOSTS = new Set<string>(${JSON.stringify(have, null, 2)});`,
  "",
].join("\n"));
console.log(`wrote ${MANIFEST}: ${have.length} hosts`);
